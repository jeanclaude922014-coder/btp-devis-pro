    nom: str
    h: float
    b: float
    tw: float
    tf: float
    A: float
    kg: float
    Iy: float
    Wely: float
    Wply: float
    Iz: float
    It: float
    Iw: float

    @property
    def iy(self):
        return (self.Iy / self.A) ** 0.5

    @property
    def iz(self):
        return (self.Iz / self.A) ** 0.5

    @property
    def Avz(self):
        """Aire de cisaillement approchée (cm²) : h × tw."""
        return self.h * self.tw / 100


